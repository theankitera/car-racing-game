const range = (v: number, lo: number, hi: number) => clamp((v - lo) / (hi - lo), 0.04, 1)

function statsFor(c: RawCar): CarStatBars {
  return {
    speed: range(c.maxSpeed, 60, 100),
    accel: range(c.power / c.mass, 6.6, 14),
    handling: range(c.grip, 11, 16.5),
    braking: range(c.brake, 11000, 16000),
  }
}

export const CARS: CarSpec[] = RAW.map((c) => ({ ...c, stats: statsFor(c) }))

export const STARTER_CAR = 'kestrel'

export function getCar(id: string): CarSpec {
  return CARS.find((c) => c.id === id) ?? CARS[0]
}
